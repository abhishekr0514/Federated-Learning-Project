import React, { useCallback, useEffect, useState } from 'react';
import { apiRequest, ApiError } from '../../services/api';
import { AlertCircle, BarChart3, RefreshCw, FileText } from 'lucide-react';

function fmtPct(value) {
  if (value == null || Number.isNaN(Number(value))) return '—';
  return `${(Number(value) * 100).toFixed(2)}%`;
}

function fmtNum(value, digits = 4) {
  if (value == null || Number.isNaN(Number(value))) return '—';
  return Number(value).toFixed(digits);
}

function ModelMetricsCard({ modelId, data }) {
  if (!data) return null;
  const cm = data.confusion_matrix_raw?.matrix;
  return (
    <div className="card" style={{ marginBottom: '1rem' }}>
      <div className="card-header">
        <div className="card-icon text-info">
          <BarChart3 size={18} />
        </div>
        <div className="card-title">{modelId.replace(/_/g, ' ')}</div>
      </div>
      <div style={{ fontSize: '0.8125rem', display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(140px, 1fr))', gap: '0.75rem' }}>
        <div><strong>n (test)</strong><br />{data.n_samples ?? '—'}</div>
        <div><strong>AUROC</strong><br />{fmtNum(data.auroc)}</div>
        <div><strong>Accuracy</strong><br />{fmtPct(data.accuracy)}</div>
        <div><strong>Balanced acc</strong><br />{fmtPct(data.balanced_accuracy)}</div>
        <div><strong>Macro F1</strong><br />{fmtPct(data.macro_f1)}</div>
        <div><strong>Class-1 recall</strong><br />{fmtPct(data.class_1_recall_sensitivity)}</div>
        <div><strong>Class-0 specificity</strong><br />{fmtPct(data.class_0_specificity)}</div>
        <div><strong>MCC</strong><br />{fmtNum(data.mcc)}</div>
      </div>
      {cm && (
        <div style={{ marginTop: '1rem', fontSize: '0.75rem' }}>
          <strong>Confusion matrix</strong> (rows=actual, cols=predicted — NORM, MI/STTC)
          <pre style={{ marginTop: '0.35rem', padding: '0.5rem', background: 'var(--bg-secondary)', borderRadius: 4 }}>
            {JSON.stringify(cm, null, 2)}
          </pre>
        </div>
      )}
      {data.score_semantics && (
        <p style={{ fontSize: '0.7rem', color: 'var(--text-muted)', marginTop: '0.5rem' }}>
          AUROC uses {data.score_semantics}. {data.confidence_note || ''}
        </p>
      )}
    </div>
  );
}

export function GlobalEvaluationMetricsPanel() {
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [data, setData] = useState(null);

  const load = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await apiRequest('/api/v1/admin/metrics');
      setData(res?.data ?? res);
    } catch (err) {
      setError(err instanceof ApiError ? err.message : err?.message || 'Failed to load metrics');
      setData(null);
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  if (loading) {
    return (
      <div className="card" style={{ padding: '1.5rem', textAlign: 'center' }}>
        <RefreshCw size={20} className="animate-spin" style={{ display: 'inline', marginRight: 8 }} />
        Loading offline evaluation report…
      </div>
    );
  }

  if (error) {
    return (
      <div className="card" style={{ borderLeft: '3px solid var(--danger)', padding: '1rem' }}>
        <AlertCircle size={18} style={{ display: 'inline', marginRight: 6, color: 'var(--danger)' }} />
        {error}
        <button type="button" className="btn btn-secondary btn-sm" onClick={load} style={{ marginLeft: '1rem' }}>
          Retry
        </button>
      </div>
    );
  }

  if (data?.status === 'REPORT_NOT_FOUND' || data?.status === 'REPORT_INVALID') {
    return (
      <div className="card">
        <div className="card-title" style={{ marginBottom: '0.5rem' }}>No evaluation report on disk</div>
        <p style={{ fontSize: '0.875rem', color: 'var(--text-muted)' }}>{data.message}</p>
        <p style={{ fontSize: '0.8125rem', marginTop: '0.75rem' }}>
          Expected folder: <code>{data.expected_directory || 'reports/model_evaluation'}</code>
        </p>
      </div>
    );
  }

  if (data?.status !== 'AVAILABLE') {
    return (
      <div className="card">
        <p style={{ color: 'var(--text-muted)' }}>{data?.message || 'Metrics unavailable.'}</p>
      </div>
    );
  }

  const models = data.models || {};
  const ds = data.dataset || {};

  return (
    <div>
      <div className="notice-banner" style={{ marginBottom: '1rem', fontSize: '0.8125rem' }}>
        <strong>Zero Mock Data:</strong> Values below are read from{' '}
        <code>{data.report_artifacts?.directory || 'reports/model_evaluation'}</code> generated by{' '}
        <code>scripts/generate_model_evaluation_report.py</code>. {data.research_disclaimer}
      </div>

      <div className="card" style={{ marginBottom: '1rem' }}>
        <div className="card-header">
          <div className="card-icon text-info">
            <FileText size={18} />
          </div>
          <div className="card-title">Evaluation run metadata</div>
        </div>
        <div style={{ fontSize: '0.8125rem', lineHeight: 1.6 }}>
          <div><strong>Generated (UTC):</strong> {data.generated_at_utc || '—'}</div>
          <div><strong>Test examples in bundle:</strong> {ds.test_in_bundle ?? '—'} (eligible full split: {ds.test_eligible_full_split ?? '—'})</div>
          <div><strong>Test split mode:</strong> {ds.test_split_mode ?? '—'}</div>
          <div><strong>Target:</strong> {ds.target_definition || '—'}</div>
          <div><strong>Classes:</strong> {JSON.stringify(data.class_mapping || {})}</div>
        </div>
      </div>

      {Object.entries(models).map(([id, block]) => (
        <ModelMetricsCard key={id} modelId={id} data={block} />
      ))}

      <div className="card" style={{ fontSize: '0.8125rem', color: 'var(--text-muted)' }}>
        <strong>Static artifacts</strong> (open locally):{' '}
        {Object.values(data.report_artifacts?.files || {}).join(', ')}
      </div>
    </div>
  );
}
